/**
 * gallery.js — Renderiza la galería por año/etapa y controla el modal
 * (lightbox) con navegación anterior/siguiente, teclado y cierre.
 */
(function () {
    "use strict";

    const TABS = [
        { key: "nacimiento", label: "Nacimiento" },
        { key: "2024", label: "2024" },
        { key: "2025", label: "2025" },
        { key: "2026", label: "2026" }
    ];

    let activeKey = "nacimiento";
    let activeList = [];
    let activeIndex = 0;

    function renderTabs(container) {
        const wrap = document.createElement("div");
        wrap.className = "gallery-tabs";
        wrap.setAttribute("role", "tablist");
        TABS.forEach((tab) => {
            const btn = document.createElement("button");
            btn.type = "button";
            btn.className = "gallery-tab" + (tab.key === activeKey ? " is-active" : "");
            btn.textContent = tab.label;
            btn.setAttribute("role", "tab");
            btn.setAttribute("aria-selected", tab.key === activeKey ? "true" : "false");
            btn.addEventListener("click", () => {
                activeKey = tab.key;
                renderGrid();
                wrap.querySelectorAll(".gallery-tab").forEach((b) => {
                    b.classList.remove("is-active");
                    b.setAttribute("aria-selected", "false");
                });
                btn.classList.add("is-active");
                btn.setAttribute("aria-selected", "true");
            });
            wrap.appendChild(btn);
        });
        container.appendChild(wrap);
    }

    function renderGrid() {
        const grid = document.getElementById("gallery-grid");
        if (!grid) return;
        grid.innerHTML = "";

        const photos = GALLERY_DATA[activeKey] || [];

        if (photos.length === 0) {
            const empty = document.createElement("p");
            empty.className = "section-subtitle";
            empty.style.textAlign = "center";
            empty.style.gridColumn = "1 / -1";
            empty.textContent = "Este capítulo todavía está esperando sus primeras fotografías. ¡Pronto estarán aquí!";
            grid.appendChild(empty);
            return;
        }

        photos.forEach((photo, index) => {
            const img = document.createElement("img");
            img.src = photo.src;
            img.alt = photo.caption + " — " + window.CONFIG.nombreCorto;
            img.loading = "lazy";
            img.tabIndex = 0;
            img.setAttribute("role", "button");
            img.addEventListener("click", () => openModal(activeKey, index));
            img.addEventListener("keyup", (e) => {
                if (e.key === "Enter" || e.key === " ") openModal(activeKey, index);
            });
            grid.appendChild(img);
        });
    }

    /* ---------- Modal / Lightbox ---------- */
    function ensureModal() {
        let modal = document.getElementById("photo-modal");
        if (modal) return modal;

        modal = document.createElement("div");
        modal.id = "photo-modal";
        modal.className = "photo-modal";
        modal.setAttribute("role", "dialog");
        modal.setAttribute("aria-modal", "true");
        modal.innerHTML = `
            <div class="photo-modal-inner">
                <button type="button" class="photo-modal-close" aria-label="Cerrar foto">✕</button>
                <button type="button" class="photo-modal-nav prev" aria-label="Foto anterior">‹</button>
                <img id="photo-modal-img" src="" alt="">
                <button type="button" class="photo-modal-nav next" aria-label="Foto siguiente">›</button>
                <p class="photo-modal-caption" id="photo-modal-caption"></p>
            </div>`;
        document.body.appendChild(modal);

        modal.querySelector(".photo-modal-close").addEventListener("click", closeModal);
        modal.querySelector(".photo-modal-nav.prev").addEventListener("click", () => navigate(-1));
        modal.querySelector(".photo-modal-nav.next").addEventListener("click", () => navigate(1));
        modal.addEventListener("click", (e) => {
            if (e.target === modal) closeModal();
        });
        document.addEventListener("keydown", (e) => {
            if (!modal.classList.contains("is-open")) return;
            if (e.key === "Escape") closeModal();
            if (e.key === "ArrowLeft") navigate(-1);
            if (e.key === "ArrowRight") navigate(1);
        });

        return modal;
    }

    function openModal(key, index) {
        activeList = GALLERY_DATA[key] || [];
        if (!activeList.length) return;
        activeIndex = index;
        const modal = ensureModal();
        updateModalContent();
        modal.classList.add("is-open");
    }

    function updateModalContent() {
        const modal = document.getElementById("photo-modal");
        if (!modal) return;
        const photo = activeList[activeIndex];
        const img = modal.querySelector("#photo-modal-img");
        const caption = modal.querySelector("#photo-modal-caption");
        img.src = photo.src;
        img.alt = photo.caption + " — " + window.CONFIG.nombreCorto;
        caption.textContent = photo.caption;
    }

    function navigate(delta) {
        if (!activeList.length) return;
        activeIndex = (activeIndex + delta + activeList.length) % activeList.length;
        updateModalContent();
    }

    function closeModal() {
        const modal = document.getElementById("photo-modal");
        if (modal) modal.classList.remove("is-open");
    }

    /** Permite abrir el modal desde fotografías fuera de la galería principal
     * (tarjetas de la línea de tiempo, polaroids, cumpleaños) usando el
     * atributo data-lightbox con la ruta de la imagen. */
    function bindExternalTriggers() {
        document.addEventListener("click", (e) => {
            const target = e.target.closest("[data-lightbox]");
            if (!target) return;
            const src = target.dataset.lightbox;
            const caption = target.dataset.caption || "";
            activeList = [{ src, caption }];
            activeIndex = 0;
            const modal = ensureModal();
            updateModalContent();
            modal.classList.add("is-open");
        });
    }

    function initGallery() {
        const tabsContainer = document.getElementById("gallery-tabs-container");
        if (tabsContainer) renderTabs(tabsContainer);
        renderGrid();
        bindExternalTriggers();
    }

    window.ValeriaGallery = { initGallery, GALLERY_DATA };
})();
